export type ForkLocale = keyof typeof forkTranslations;

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function mergeRecords(
  base: Record<string, unknown>,
  overlay: Record<string, unknown>,
): Record<string, unknown> {
  const merged = { ...base };
  for (const [key, value] of Object.entries(overlay)) {
    const baseValue = merged[key];
    merged[key] = isRecord(baseValue) && isRecord(value) ? mergeRecords(baseValue, value) : value;
  }
  return merged;
}

export function withForkTranslations<T extends Record<string, unknown>>(
  base: T,
  locale: ForkLocale,
): T {
  return mergeRecords(base, forkTranslations[locale]) as T;
}
